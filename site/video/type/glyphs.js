/** Columns a space takes. */
const SPACE = 3;

/** Cells of `text`: col, row from top, glyph index. */
export function cells(text) {
  const out = [];
  let col = 0;
  [...text].forEach((ch, glyph) => {
    if (ch === " ") {
      col += SPACE - 1;
      return;
    }
    const rows = SHAPES[ch];
    if (!rows) throw new Error(`no glyph for ${ch}`);
    rows.forEach((line, row) =>
      [...line].forEach((c, i) => {
        if (c === "#") out.push({ col: col + i, row, glyph });
      }),
    );
    col += rows[0].length + 1;
  });
  return { cells: out, width: col - 1 };
}
